#!/usr/bin/env python3
"""Build ~/.config/wayfire.ini from base.ini + hosts/<host>.ini.

Merge is per key: a host key overrides the base key of the same name in the
same section; host-only keys and sections are appended. Placeholders:
  @HOME@      -> $HOME
  @DOTFILES@  -> the repo root (parent of this script's folder)

Usage: build.py [host]   (default: derived from the hostname)
"""
import os
import socket
import sys
from pathlib import Path

HOSTS = {"azur3x-xps": "xps", "azur3x-desktop": "desktop"}

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
OUT = Path.home() / ".config" / "wayfire.ini"


def parse(path):
    """Return {section: {key: value}} preserving order; values keep '\\' continuations."""
    sections, cur, pending = {}, None, None
    for raw in path.read_text().splitlines():
        if pending is not None:
            sections[cur][pending] += "\n" + raw
            if not raw.rstrip().endswith("\\"):
                pending = None
            continue
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("[") and line.endswith("]"):
            cur = line[1:-1].strip()
            sections.setdefault(cur, {})
            continue
        if cur is None or "=" not in line:
            sys.exit(f"{path}: cannot parse line: {raw!r}")
        key, val = (s.strip() for s in line.split("=", 1))
        sections[cur][key] = val
        if val.endswith("\\"):
            pending = key
    return sections


def merge(base, host):
    out = {s: dict(kv) for s, kv in base.items()}
    for sec, kv in host.items():
        out.setdefault(sec, {}).update(kv)
    return out


def render(cfg, host):
    lines = [
        "# GENERATED by wayfire/build.py — do not edit.",
        f"# Edit wayfire/base.ini or wayfire/hosts/{host}.ini in the dotfiles repo, then rerun the script.",
        "",
    ]
    for sec, kv in cfg.items():
        lines.append(f"[{sec}]")
        lines += [f"{k} = {v}" for k, v in kv.items()]
        lines.append("")
    text = "\n".join(lines)
    return text.replace("@HOME@", str(Path.home())).replace("@DOTFILES@", str(REPO))


def main():
    host = sys.argv[1] if len(sys.argv) > 1 else HOSTS.get(socket.gethostname())
    if not host:
        sys.exit(f"Unknown hostname {socket.gethostname()!r}; pass the host name as an argument.")
    host_file = HERE / "hosts" / f"{host}.ini"
    if not host_file.is_file():
        sys.exit(f"No host file: {host_file}")
    text = render(merge(parse(HERE / "base.ini"), parse(host_file)), host)
    if OUT.is_symlink():
        sys.exit(f"{OUT} is a symlink; remove it first.")
    # Write in place (no rename) so Wayfire's file watch keeps working.
    with open(OUT, "w") as f:
        f.write(text)
    print(f"Wrote {OUT} from base.ini + hosts/{host}.ini")


if __name__ == "__main__":
    main()
